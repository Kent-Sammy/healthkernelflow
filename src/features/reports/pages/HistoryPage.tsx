import { useMemo, useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { Download, Eye, RefreshCw } from 'lucide-react'
import { useUiStore } from '@/state/uiStore'
import { useDb } from '../data/useDb'
import { MODULES, MODULE_BY_ID, REPORT_BY_ID } from '../engine/catalogue'
import { SOURCES } from '../engine/sources'
import { configPeriod, periodApplies, runReport, scopeRows } from '../engine/run'
import { configToSearch } from '../engine/url'
import { periodLabel } from '../engine/period'
import { csvValue } from '../engine/format'
import { downloadCsv, slug } from '../engine/csv'
import { useReportsStore, type HistoryEntry } from '../state/reportsStore'
import { DataTable } from '../components/DataTable'
import { DemoNotice, HkButton, KpiCard, ModuleIcon, NativeSelect, PageHeader, Panel, StatusBadge } from '../components/ui'

export function HistoryPage() {
  const db = useDb()
  const history = useReportsStore((s) => s.history)
  const logAudit = useReportsStore((s) => s.logAudit)
  const toast = useUiStore((s) => s.showToast)
  const navigate = useNavigate()
  const [module, setModule] = useState('all')
  const [status, setStatus] = useState('all')
  const [who, setWho] = useState('all')

  const rows = useMemo(() => {
    return history
      .filter((h) => REPORT_BY_ID[h.config.reportId])
      .map((h) => {
        const def = REPORT_BY_ID[h.config.reportId]
        const src = SOURCES[def.source]
        const period = configPeriod(h.config)
        const records = h.status === 'Failed' ? 0 : (h.rows ?? scopeRows(db, def, h.config, period).length)
        return { ...h, def, module: MODULE_BY_ID[def.module].label, periodText: periodApplies(def, src) ? periodLabel(period) : 'Snapshot', records }
      })
  }, [history, db])
  const people = [...new Set(rows.map((r) => r.generatedBy))].sort()
  const filtered = rows.filter((r) => (module === 'all' || r.def.module === module) && (status === 'all' || r.status === status) && (who === 'all' || r.generatedBy === who))

  const download = (h: HistoryEntry) => {
    const r = runReport(db, h.config)
    downloadCsv(`${slug(r.def.name)}_${r.period.from}_${r.period.to}_records`, r.columns.map((c) => c.label), r.detailRows.map((x) => r.columns.map((c) => csvValue(c.get(x), c.fmt))))
    logAudit({ action: 'Report exported (CSV)', category: 'Export', target: r.def.name, details: `${r.detailRows.length.toLocaleString()} records exported from history` })
    toast({ title: 'CSV exported', description: `${r.detailRows.length.toLocaleString()} rows downloaded.`, variant: 'success' })
  }

  type R = (typeof rows)[number]
  return (
    <div className="flex flex-col gap-6">
      <PageHeader title="Report History" subtitle="Every report generated by your team and the scheduler, with the exact configuration used." eyebrow={<DemoNotice />} />
      <div className="grid grid-cols-2 gap-4 lg:grid-cols-4">
        <KpiCard label="Reports generated" value={rows.length} fmt="number" sub="Retained history" />
        <KpiCard label="Generated today" value={rows.filter((r) => r.generatedAt.startsWith('2026-10-27')).length} fmt="number" sub="27 Oct 2026" />
        <KpiCard label="Scheduled runs" value={rows.filter((r) => r.status === 'Scheduled run').length} fmt="number" sub="Delivered by scheduler" />
        <KpiCard label="Failed" value={rows.filter((r) => r.status === 'Failed').length} fmt="number" sub="Retry available" />
      </div>
      <Panel>
        <DataTable
          rows={filtered}
          rowKey={(r) => r.id}
          onRowClick={(r) => navigate(`/reports/view${configToSearch(r.config)}`)}
          searchPlaceholder="Search report, period or user…"
          initialSort={{ id: 'generatedAt', dir: 'desc' }}
          toolbar={
            <div className="grid grid-cols-3 gap-2.5">
              <NativeSelect value={module} onChange={(e) => setModule(e.target.value)} options={[{ value: 'all', label: 'All modules' }, ...MODULES.map((m) => ({ value: m.id, label: m.label }))]} aria-label="Module" />
              <NativeSelect value={status} onChange={(e) => setStatus(e.target.value)} options={['all', 'Completed', 'Scheduled run', 'Failed'].map((v) => ({ value: v, label: v === 'all' ? 'All statuses' : v }))} aria-label="Status" />
              <NativeSelect value={who} onChange={(e) => setWho(e.target.value)} options={[{ value: 'all', label: 'Anyone' }, ...people.map((p) => ({ value: p, label: p }))]} aria-label="Generated by" />
            </div>
          }
          columns={[
            {
              id: 'name',
              label: 'Report',
              get: (r: R) => r.def.name,
              render: (r: R) => (
                <span className="flex items-center gap-2.5">
                  <ModuleIcon module={r.def.module} size="sm" />
                  <span>
                    <span className="block font-semibold">{r.def.name}</span>
                    {r.note && <span className="block text-[11.5px] text-danger-700">{r.note}</span>}
                  </span>
                </span>
              ),
            },
            { id: 'module', label: 'Module', get: (r: R) => r.module },
            { id: 'period', label: 'Reporting period', get: (r: R) => r.periodText },
            { id: 'generatedAt', label: 'Generated', fmt: 'datetime', get: (r: R) => r.generatedAt },
            { id: 'generatedBy', label: 'Generated by', get: (r: R) => r.generatedBy },
            { id: 'records', label: 'Records', fmt: 'number', get: (r: R) => r.records },
            { id: 'status', label: 'Status', get: (r: R) => r.status, render: (r: R) => <StatusBadge value={r.status} /> },
            {
              id: 'actions',
              label: 'Actions',
              sortable: false,
              get: () => '',
              render: (r: R) => (
                <span className="flex gap-1" onClick={(e) => e.stopPropagation()}>
                  {r.status === 'Failed' ? (
                    <HkButton size="sm" variant="outline" onClick={() => navigate(`/reports/view${configToSearch(r.config)}`)}>
                      <RefreshCw /> Retry
                    </HkButton>
                  ) : (
                    <>
                      <HkButton size="sm" variant="ghost" onClick={() => navigate(`/reports/view${configToSearch(r.config)}`)} aria-label="View report">
                        <Eye /> View
                      </HkButton>
                      <HkButton size="sm" variant="ghost" onClick={() => download(r)} aria-label="Download CSV">
                        <Download /> CSV
                      </HkButton>
                    </>
                  )}
                </span>
              ),
            },
          ]}
        />
      </Panel>
    </div>
  )
}
